function renderDBFLTeam(){
  const root=document.getElementById('teamDirectory');
  if(!root)return;
  root.innerHTML=`<div class="team-directory"><div class="team-directory-head"><div><p class="kicker">Our people</p><h2>Meet more of the team</h2><p><span id="teamCount">${DBFL_TEAM.length}</span> people currently featured in this concept.</p></div><input class="team-search" id="teamSearch" type="search" placeholder="Search by name" aria-label="Search team members"></div><div class="team-photo-grid" id="teamPhotoGrid"></div><p class="team-empty" id="teamEmpty">No matching team member found.</p></div>`;
  const grid=document.getElementById('teamPhotoGrid');
  const empty=document.getElementById('teamEmpty');
  const count=document.getElementById('teamCount');
  const draw=(query='')=>{
    const term=query.trim().toLowerCase();
    const matches=DBFL_TEAM.filter(person=>person.name.toLowerCase().includes(term));
    grid.innerHTML=matches.map(person=>`<figure class="team-photo-card"><img src="${person.image}" alt="${DBFLContent.escape(person.name)}" loading="lazy"><figcaption>${DBFLContent.escape(person.name)}</figcaption></figure>`).join('');
    count.textContent=matches.length;
    empty.style.display=matches.length?'none':'block';
  };
  document.getElementById('teamSearch').addEventListener('input',event=>draw(event.target.value));
  draw();
}
window.DBFLTeam={people:DBFL_TEAM,render:renderDBFLTeam};

